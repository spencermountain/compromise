import fs from 'node:fs'
import packLexicon from './lexicon.js'
import packConjugations from './conjugations.js'
import packProperNouns from './properNouns.js'

const steps = [
  { name: 'lexicon', file: '2-two/_built/lexicon.js', pack: packLexicon },
  { name: 'conjugations', file: '2-two/_built/conjugations.js', pack: packConjugations },
  // a subset of the lexicon, for other languages
  { name: 'properNouns', file: 'shared/lexicon/_built.js', pack: packProperNouns },
]
const banner = '// Generated by scripts/pack/index.js; see data/README.md for source files.\n'

steps.forEach(({ name, file: path, pack }) => {
  console.log(`\n 🕑  - packing ${name}..`)
  const packed = pack()
  const file = new URL(`../../src/${path}`, import.meta.url)
  fs.mkdirSync(new URL('./', file), { recursive: true })
  fs.writeFileSync(file, banner + 'export default ' + JSON.stringify(packed, null, 2), 'utf8')
  const size = (fs.statSync(file).size / 1000).toFixed(1)
  console.log(`       - ${name} is ${size}k\n`)
})
